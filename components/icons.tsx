import { brandIcons } from "@/data/brand-icons";

type IconProps = { size?: number; className?: string };

function brand(name: keyof typeof brandIcons, { size = 17, className = "" }: IconProps) {
  const icon = brandIcons[name];
  if (!icon) return null;
  return (
    <svg
      width={size}
      height={size}
      viewBox={icon.viewBox}
      fill="currentColor"
      className={className}
      aria-hidden="true"
    >
      <path d={icon.d} />
    </svg>
  );
}

